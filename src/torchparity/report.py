"""Markdown report from saved results."""

from __future__ import annotations

import datetime
import json
from collections import Counter, defaultdict
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # Python < 3.11
    import tomli as tomllib

from .cases import op_table

ICONS = {"ok": "✅", "wrong": "❌", "edge": "⚠️", "unsupported": "🚫", "skip": "–"}
SEVERITY = ("wrong", "edge", "unsupported")
LEGEND = ("✅ same as eager PyTorch · ❌ wrong result on ordinary values, or wrong dtype · "
          "⚠️ differs only on edge values (NaN, ±inf, -0.0, |x| ≥ 1e6 or < 1e-6, integer overflow, "
          "division by zero) · 🚫 fails to convert or run · – not checked")


def load_results(paths) -> list[dict]:
    runs = [json.loads(Path(p).read_text(encoding="utf-8")) for p in paths]
    order = ["onnx", "openvino", "coreml", "tensorrt", "executorch", "inductor"]
    return sorted(runs, key=lambda r: order.index(r["backend"]) if r["backend"] in order else len(order))


def load_known(path) -> list[dict]:
    if not path or not Path(path).exists():
        return []
    return tomllib.loads(Path(path).read_text(encoding="utf-8")).get("issue", [])


def _link(url: str) -> str:
    return f"[#{url.rstrip('/').rsplit('/', 1)[-1]}]({url})"


def _known_links(known, backend, op, dtypes) -> list[str]:
    links = []
    for item in known:
        if item["backend"] != backend or op not in item["ops"]:
            continue
        wanted = item.get("dtypes")
        if wanted and not any(d in wanted or any(part in wanted for part in d.split("+")) for d in dtypes):
            continue
        links.append(_link(item.get("issue") or item["pr"]))
    return links


def _cell(results: list[dict], links: list[str]) -> str:
    if not results:
        return ""
    by_status = defaultdict(list)
    for r in results:
        by_status[r["status"]].append(r["dtype"])
    parts = [f"{ICONS[s]} {' '.join(by_status[s])}" for s in SEVERITY if by_status[s]]
    if not parts:
        return ICONS["ok"] if by_status["ok"] else ICONS["skip"]
    return " · ".join(parts) + ("".join(f" {link}" for link in links))


def _example(r: dict) -> str:
    if r["status"] == "unsupported" or not r["examples"]:
        return r["detail"].replace("|", "\\|")
    shown = []
    for ex in r["examples"][:2]:
        inputs = ", ".join(f"{k}={v}" for k, v in ex.get("inputs", {}).items())
        shown.append(f"{inputs + ': ' if inputs else ''}eager {ex['eager']}, got {ex['backend']}")
    return "; ".join(shown).replace("|", "\\|")


def render_found(known: list[dict]) -> str:
    """Table of the issues found with torchparity, with live status badges."""
    rows = ["| Project | Problem | Status |", "|---|---|---|"]
    for item in known:
        if not item.get("found_here"):
            continue
        url = item.get("pr") or item["issue"]
        owner, repo, kind, number = url.rstrip("/").split("/")[-4:]
        kinds = "pulls" if kind == "pull" else "issues"
        badge = f"https://img.shields.io/github/{kinds}/detail/state/{owner}/{repo}/{number}"
        problem = item["title"].replace("|", "\\|")
        if item.get("pr") and item.get("issue"):
            problem += f" ([issue]({item['issue']}))"
        rows.append(f"| {owner}/{repo} | {problem} | [![{kind} {number}]({badge})]({url}) |")
    return "\n".join(rows)


def update_readme(path, known: list[dict]) -> None:
    text = Path(path).read_text(encoding="utf-8")
    start, end = "<!-- found:start -->", "<!-- found:end -->"
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    Path(path).write_text(f"{head}{start}\n{render_found(known)}\n{end}{tail}", encoding="utf-8")


def render(runs: list[dict], known: list[dict]) -> str:
    table = op_table()
    lines = [
        "# Results",
        "",
        f"Generated by `torchparity report` on {datetime.date.today().isoformat()}. Each backend's output is "
        "compared with eager PyTorch on the same inputs. Differences from eager PyTorch are not always bugs: "
        "some are documented limitations or deliberate choices.",
        "",
        "| Backend | Versions | How it runs | ✅ | ❌ | ⚠️ | 🚫 |",
        "|---|---|---|---|---|---|---|",
    ]
    for run in runs:
        counts = Counter(r["status"] for r in run["results"])
        versions = ", ".join(f"{k} {v}" for k, v in run["versions"].items())
        lines.append(f"| {run['label']} | {versions} | {run['mode']} | {counts['ok']} | {counts['wrong']} | "
                     f"{counts['edge']} | {counts['unsupported']} |")
    lines += ["", LEGEND, "", "## By operator", ""]
    lines.append("| Op | Expression | " + " | ".join(run["label"] for run in runs) + " |")
    lines.append("|---|---|" + "---|" * len(runs))
    ops = list(table) + sorted({r["op"] for run in runs for r in run["results"]} - set(table))
    for op in ops:
        exprs = table.get(op, {})
        expr = " / ".join(dict.fromkeys(exprs.values())) or next(
            (r["expr"] for run in runs for r in run["results"] if r["op"] == op), "")
        cells = []
        for run in runs:
            results = [r for r in run["results"] if r["op"] == op]
            bad = [r["dtype"] for r in results if r["status"] in SEVERITY]
            cells.append(_cell(results, _known_links(known, run["backend"], op, bad)))
        if any(cells):
            lines.append(f"| `{op}` | `{expr}` | " + " | ".join(cells) + " |")
    lines += ["", "## Details", ""]
    for run in runs:
        bad = [r for r in run["results"] if r["status"] in SEVERITY]
        lines += [f"<details><summary><b>{run['label']}</b>: {len(bad)} cases differ or fail</summary>", "",
                  "| Case | | Example or error |", "|---|---|---|"]
        for r in sorted(bad, key=lambda r: (SEVERITY.index(r["status"]), r["op"], r["dtype"])):
            lines.append(f"| `{r['op']}` {r['dtype']} | {ICONS[r['status']]} | {_example(r)} |")
        lines += ["", "</details>", ""]
    return "\n".join(lines)
